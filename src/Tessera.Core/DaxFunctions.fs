/// The names of DAX's built-in functions, for the unknown-function rule (Validate). Names only: what
/// a function takes or returns is the parser's and the engine's business.
///
/// Sources, read 2026-11-15:
///   - Microsoft Learn's DAX function reference: every function page in its table of contents,
///     https://learn.microsoft.com/en-us/dax/toc.json (460 functions; "DISTINCT (column)" and
///     "DISTINCT (table)" are one name). The MicrosoftDocs/query-docs repository behind it isn't
///     public (GitHub answers 404), so the TOC is the list.
///   - dax.guide's function list, https://dax.guide/functions/ (525 entries). It has every name in
///     Learn's list, plus the functions in `daxGuideOnly` below (visual calculation functions, ones
///     Power BI's own queries use, deprecated ones the engine still accepts). Its other entries
///     are operators, statements, keywords and data types (EVALUATE, VAR, ORDER BY, INTEGER,
///     DENSIFY, ...), which DAX never calls, so they're left out.
///
/// When Microsoft adds a function, add it to `learn` (and note the date here): until then
/// `tess validate` reports a call to it as an unknown-function error, and the save gate and
/// `deploy` refuse an edit that introduces one (unless --force).
