/// On dax.guide but not in Learn's reference.
let private daxGuideOnly =
    """
    ALLSELECTEDAPPLY ALLSELECTEDREMOVE ALWAYSAPPLY COLLAPSE COLLAPSEALL DEPENDON EXPAND EXPANDALL
    FILTERCLUSTER FIRST GROUPCROSSAPPLY GROUPCROSSAPPLYTABLE HASH ISATLEVEL KEYWORDMATCH LAST
    NATURALJOINUSAGE NEXT NONFILTER PREVIOUS SAMPLEAXISWITHLOCALMINMAX SHADOWCLUSTER TOPNPERLEVEL
    TOPNSKIP
    """

let private words (s: string) =
    s.Split([| ' '; '\r'; '\n' |], StringSplitOptions.RemoveEmptyEntries)

/// Every built-in DAX function name, upper case, sorted.
let all: string list =
    Array.append (words learn) (words daxGuideOnly)
    |> Array.distinct
    |> Array.sort
    |> List.ofArray

let private set = HashSet<string>(all, StringComparer.OrdinalIgnoreCase)

/// Whether `name` is a built-in DAX function (case-insensitive, like DAX).
let isBuiltIn (name: string) = set.Contains name
